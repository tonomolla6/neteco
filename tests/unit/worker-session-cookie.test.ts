import { describe, expect, it } from 'vitest'
import { IncomingMessage, ServerResponse } from 'node:http'
import { Socket } from 'node:net'
import { createEvent, sealSession } from 'h3'
import { defaults, seal } from 'iron-webcrypto'
import { verifySessionCookie } from '../../workers/auth/session-cookie'
import { ironCrypto } from '../../workers/auth/iron-crypto'

const password = 'test-only-neteco-session-secret-with-at-least-32-characters'
const configuration = { password, maxAgeSeconds: 60 }
const claims = {
  sessionId: '10000000-0000-4000-8000-000000000001',
  identityId: '20000000-0000-4000-8000-000000000001',
  sessionVersion: 3
}
function data() {
  return {
    sessionId: claims.sessionId,
    sessionVersion: claims.sessionVersion,
    user: { id: claims.identityId, roles: ['admin'], mfaVerified: true }
  }
}
function request(cookie?: string) {
  return new Request('https://neteco.invalid/api/admin/media', { headers: cookie ? { cookie } : {} })
}
async function signed(value: unknown) {
  return seal(ironCrypto, value, password, { ...defaults, ttl: 60_000 })
}

describe('Worker verification of Nuxt session cookies', () => {
  it('accepts an envelope generated by the installed h3 implementation, ignoring cached grants', async () => {
    const socket = new Socket()
    try {
      const incoming = new IncomingMessage(socket)
      const event = createEvent(incoming, new ServerResponse(incoming))
      event.context.sessions = { 'neteco-session': { id: crypto.randomUUID(), createdAt: Date.now(), data: data() } }
      const cookie = await sealSession(event, { name: 'neteco-session', password, maxAge: 60 })
      expect(
        await verifySessionCookie(
          request(`other=x; neteco-session=${encodeURIComponent(cookie)}; another=y`),
          configuration
        )
      ).toEqual(claims)
    } finally {
      socket.destroy()
    }
  })

  it('rejects changed signatures, different secrets, duplicates and malformed encoding', async () => {
    const cookie = await signed({ id: crypto.randomUUID(), createdAt: Date.now(), data: data() })
    const altered = `${cookie.slice(0, -3)}xxx`
    for (const header of [
      `neteco-session=${altered}`,
      `neteco-session=${cookie}; neteco-session=${cookie}`,
      'neteco-session=%ZZ',
      'neteco-session=',
      `other=${cookie}`,
      `neteco-session=${'x'.repeat(4097)}`
    ])
      expect(await verifySessionCookie(request(header), configuration)).toBeNull()
    expect(
      await verifySessionCookie(request(`neteco-session=${cookie}`), {
        ...configuration,
        password: 'another-test-only-secret-with-at-least-32-characters'
      })
    ).toBeNull()
  })

  it('does not authenticate headers, query strings or request bodies instead of cookies', async () => {
    const cookie = await signed({ id: crypto.randomUUID(), createdAt: Date.now(), data: data() })
    const supplied = new Request(`https://neteco.invalid/?session=${encodeURIComponent(cookie)}`, {
      method: 'POST',
      headers: { 'x-neteco-session-session': cookie, authorization: `Bearer ${cookie}` },
      body: JSON.stringify(data())
    })
    expect(await verifySessionCookie(supplied, configuration)).toBeNull()
  })

  it.each([-120_000, 120_000])('rejects session age outside the permitted interval (%s)', async (offset) => {
    const cookie = await signed({ id: crypto.randomUUID(), createdAt: Date.now() + offset, data: data() })
    expect(await verifySessionCookie(request(`neteco-session=${cookie}`), configuration)).toBeNull()
  })

  it.each([
    { sessionId: claims.sessionId, sessionVersion: 0, user: { id: claims.identityId } },
    { sessionId: 'not-a-uuid', sessionVersion: 3, user: { id: claims.identityId } },
    { sessionId: claims.sessionId, sessionVersion: 3, user: { id: 'not-a-uuid' } },
    { sessionId: claims.sessionId, sessionVersion: '3', user: { id: claims.identityId } },
    { roles: ['admin'], mfaVerified: true }
  ])('rejects malformed claims even in a correctly signed envelope', async (invalid) => {
    const cookie = await signed({ id: crypto.randomUUID(), createdAt: Date.now(), data: invalid })
    expect(await verifySessionCookie(request(`neteco-session=${cookie}`), configuration)).toBeNull()
  })

  it('fails closed on absent/weak configuration rather than using local fallback secrets', async () => {
    for (const invalid of [
      { password: '', maxAgeSeconds: 60 },
      { password: 'local-only-session-password-change-me-now', maxAgeSeconds: 60 },
      { password, maxAgeSeconds: 0 }
    ]) {
      await expect(verifySessionCookie(request(), invalid)).rejects.toThrow('invalid_session_configuration')
    }
  })
})
